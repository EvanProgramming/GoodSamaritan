def log(msg:str,as_json:bool=False,**data): console.print(json.dumps({"message":msg,**data}) if as_json else msg)
def _write_private_env(path:Path, values:dict[str,str]):
    existing={}
    if path.exists():
        for line in path.read_text().splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                key,value=line.split("=",1);existing[key]=value
    existing.update({k:v for k,v in values.items() if v})
    path.write_text("# Generated by good-samaritan setup. Do not commit this file.\n"+"\n".join(f"{k}={v}" for k,v in sorted(existing.items()))+"\n")
    path.chmod(0o600)
def _write_toml(path:Path, model_priority:list[str], models:dict[str,str], live:bool=False):
    # Keep ordinary non-secret settings in a readable, reviewable TOML file.
    base=(Path(__file__).parents[2]/"config.example.toml")
    text=base.read_text() if base.exists() else ""
    text=text.replace('dry_run = true',f'dry_run = {str(not live).lower()}').replace('allow_submit = false',f'allow_submit = {str(live).lower()}')
    text=text.replace('priority = ["groq", "gemini", "openrouter"]',"priority = ["+", ".join(f'\"{x}\"' for x in model_priority)+"]")
    for provider,model in models.items(): text=text.replace(f'{provider}_model = ""',f'{provider}_model = "{model}"')
    path.write_text(text)
@app.command()
def setup(config:Path=typer.Option(Path("config.toml")),env_file:Path=typer.Option(Path(".env")),non_interactive:bool=False):
    """Create a local config and securely collect one or more provider credentials."""
    if non_interactive:
        raise typer.BadParameter("--non-interactive is intentionally unsupported: supply configuration through environment variables instead.")
    console.print("Good Samaritan setup. Credentials stay in the local .env file (mode 600) and are never logged.")
    token=typer.prompt("Dedicated Good Samaritan GitHub classic token (repo scope)",hide_input=True)
    git_name=typer.prompt("Git commit name",default="Good Samaritan")
    git_email=typer.prompt("Git commit email")
    selected=[]; models={}; secrets={"GOOD_SAMARITAN_GITHUB_TOKEN":token,"GOOD_SAMARITAN_GIT_NAME":git_name,"GOOD_SAMARITAN_GIT_EMAIL":git_email}
    for provider,key in (("groq","GROQ_API_KEY"),("gemini","GEMINI_API_KEY"),("openrouter","OPENROUTER_API_KEY")):
        if typer.confirm(f"Configure {provider}?",default=not selected):
            value=typer.prompt(f"{provider} API key",hide_input=True)
            model=typer.prompt(f"{provider} model name")
            if value and model:selected.append(provider);models[provider]=model;secrets[key]=value
    if not selected:raise typer.BadParameter("at least one provider and model are required")
    _write_private_env(env_file,secrets);_write_toml(config,selected,models)
    console.print(f"Wrote [bold]{config}[/bold] and private [bold]{env_file}[/bold]. Run `good-samaritan doctor --config {config}` next.")
@app.command("go-live")
def go_live(config:Path=typer.Option(Path("config.toml")),interval_hours:int=typer.Option(24,min=1),yes:bool=typer.Option(False,"--yes")):
    """Enable real submissions after a preflight; then start the bounded daemon."""
    s=settings(config); db=Database(s.runtime.database_path);db.close()
    problems=[]
    if not s.github.token:problems.append("GOOD_SAMARITAN_GITHUB_TOKEN is missing")
    if not s.git_email:problems.append("GOOD_SAMARITAN_GIT_EMAIL is missing")
    if not ModelRouter(s).available():problems.append("no configured provider has both API key and model")
    try: identity=GitHub(s).user().get("login") if not problems else None
    except GitHubError as e:problems.append(f"GitHub authentication failed: {e}");identity=None
    if problems:
        for problem in problems:console.print(f"[red]Preflight failed:[/red] {problem}")
        raise typer.Exit(1)
    if not yes and not typer.confirm(f"Use GitHub account {identity} to create real PRs when safeguards pass?",default=False):
        console.print("Go-live cancelled; dry-run configuration remains unchanged.");return
    # Preserve the user's discovery, limit, and model choices; change only the
    # explicit live-submission switches.
    text=config.read_text().replace('dry_run = true','dry_run = false').replace('allow_submit = false','allow_submit = true').replace('daemon_interval_seconds = 86400',f'daemon_interval_seconds = {interval_hours*3600}')
    config.write_text(text)
    console.print("Preflight passed. Starting daemon; use Ctrl-C to stop after the current cleanup.")
    daemon(config=config)
