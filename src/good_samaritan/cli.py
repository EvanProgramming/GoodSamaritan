def enable_targeted_paid_model(s,repository:str|None):
    """Keep the configured non-DeepSeek failover order for every run."""
    # A stale DEEPSEEK_API_KEY must never silently change routing. DeepSeek is
    # intentionally excluded from autonomous and targeted contribution runs;
    # OmniRoute and the configured cloud providers are the recovery paths.
    s.models.priority=[p for p in s.models.priority if p!="deepseek"]
def log(msg:str,as_json:bool=False,**data): console.print(json.dumps({"message":msg,**data}) if as_json else msg)
def push_branch(root:Path,branch:str,token:str):
    """Push without persisting or exposing the GitHub token in the remote URL."""
    auth=base64.b64encode(f"x-access-token:{token}".encode()).decode()
    env=os.environ.copy()
    env.update({"GIT_TERMINAL_PROMPT":"0","GIT_CONFIG_COUNT":"1","GIT_CONFIG_KEY_0":"http.https://github.com/.extraheader","GIT_CONFIG_VALUE_0":f"AUTHORIZATION: basic {auth}"})
    try:
        subprocess.run(["git","push","fork",branch],cwd=root,check=True,capture_output=True,text=True,timeout=180,env=env)
    except subprocess.TimeoutExpired as error:
        raise RuntimeError("git push timed out after 180 seconds") from error
    except subprocess.CalledProcessError as error:
        detail=(error.stderr or error.stdout or "git push returned no diagnostic").strip().replace("\n"," ")[:1000]
        raise RuntimeError(f"git push failed: {detail}") from error
def _write_private_env(path:Path, values:dict[str,str]):
    existing={}
    if path.exists():
        for line in path.read_text().splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                key,value=line.split("=",1);existing[key]=value
    existing.update({k:v for k,v in values.items() if v})
    path.write_text("# Generated by good-samaritan setup. Do not commit this file.\n"+"\n".join(f"{k}={v}" for k,v in sorted(existing.items()))+"\n")
    path.chmod(0o600)
def _write_toml(path:Path, model_priority:list[str], models:dict[str,str], live:bool=False):
    # Keep ordinary non-secret settings in a readable, reviewable TOML file.
    base=(Path(__file__).parents[2]/"config.example.toml")
    text=base.read_text() if base.exists() else ""
    text=text.replace('dry_run = true',f'dry_run = {str(not live).lower()}').replace('allow_submit = false',f'allow_submit = {str(live).lower()}')
    priority="priority = ["+", ".join(f'\"{x}\"' for x in model_priority)+"]"
    for default in ('priority = ["groq", "gemini", "openrouter"]','priority = ["omniroute", "groq", "gemini", "openrouter"]'):
        text=text.replace(default,priority)
    for provider,model in models.items(): text=text.replace(f'{provider}_model = ""',f'{provider}_model = "{model}"')
    path.write_text(text)
