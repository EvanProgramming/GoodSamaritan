@app.command("go-live")
def go_live(config:Path=typer.Option(Path("config.toml")),interval_hours:int=typer.Option(24,min=1),yes:bool=typer.Option(False,"--yes")):
    """Enable real submissions after a preflight; then start the bounded daemon."""
    s=settings(config); db=Database(s.runtime.database_path);db.close()
    problems=[]
    if not s.github.token:problems.append("GOOD_SAMARITAN_GITHUB_TOKEN is missing")
    if not s.git_email:problems.append("GOOD_SAMARITAN_GIT_EMAIL is missing")
    if not ModelRouter(s).available():problems.append("no configured provider has both API key and model")
    try: identity=GitHub(s).user().get("login") if not problems else None
    except GitHubError as e:problems.append(f"GitHub authentication failed: {e}");identity=None
    if problems:
        for problem in problems:console.print(f"[red]Preflight failed:[/red] {problem}")
        raise typer.Exit(1)
    if not yes and not typer.confirm(f"Use GitHub account {identity} to create real PRs when safeguards pass?",default=False):
        console.print("Go-live cancelled; dry-run configuration remains unchanged.");return
    # Preserve the user's discovery, limit, and model choices; change only the
    # explicit live-submission switches.
    text=config.read_text().replace('dry_run = true','dry_run = false').replace('allow_submit = false','allow_submit = true').replace('daemon_interval_seconds = 86400',f'daemon_interval_seconds = {interval_hours*3600}')
    config.write_text(text)
    console.print("Preflight passed. Starting daemon; use Ctrl-C to stop after the current cleanup.")
    daemon(config=config)
